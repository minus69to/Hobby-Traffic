import { EVAL, SCENARIO_LABELS, fmt, fmtPct, stat } from '../data/results';

function Card({ title, value, sub, good }: { title: string; value: string; sub: string; good: boolean | null }) {
  return (
    <div className={`card ${good === null ? '' : good ? 'good' : 'bad'}`}>
      <div className="card-title">{title}</div>
      <div className="card-value">{value}</div>
      <div className="card-sub">{sub}</div>
    </div>
  );
}

export function KeyResults() {
  const ctrl = EVAL.summary['ppo'] ? 'ppo' : (EVAL.meta.controllers.find((c) => c.startsWith('ppo')) ?? null);
  const scen = EVAL.meta.scenarios.includes('morning_peak') ? 'morning_peak' : (EVAL.meta.scenarios[0] ?? '');
  if (!ctrl) {
    return (
      <section className="section" id="results-cards">
        <h2>Key results</h2>
        <p className="muted">No trained-policy results in <code>results/eval_summary.json</code> yet. Run <code>make train eval</code>.</p>
      </section>
    );
  }
  const wait = stat(ctrl, scen, 'mean_waiting_time');
  const ped = stat(ctrl, scen, 'ped_mean_wait');
  const p95 = stat(ctrl, scen, 'p95_travel_time');
  const thr = stat(ctrl, scen, 'throughput');
  const shield = stat(ctrl, scen, 'shield_interventions');
  const rick = stat(ctrl, scen, 'wait_rickshaw');
  const n = EVAL.summary[ctrl]?.[scen]?.n ?? 0;
  return (
    <section className="section" id="results-cards">
      <h2>Key results · {SCENARIO_LABELS[scen] ?? scen}</h2>
      <p className="muted">
        Safe PPO vs the Webster fixed-time baseline, {n} evaluation episodes of {EVAL.meta.episode_seconds} s on disjoint seeds, 95 % bootstrap confidence intervals.
        All numbers are generated by <code>make eval</code> into <code>results/eval_summary.json</code>; demand is synthetic.
      </p>
      <div className="cards">
        <Card title="Mean vehicle waiting time" value={fmtPct(wait?.pct_vs_fixed)} sub={`${fmt(wait?.mean)} s vs fixed-time · CI [${fmtPct(wait?.pct_ci_low)}, ${fmtPct(wait?.pct_ci_high)}]`} good={wait ? (wait.pct_vs_fixed ?? 0) < 0 : null} />
        <Card title="95th percentile travel time" value={fmtPct(p95?.pct_vs_fixed)} sub={`${fmt(p95?.mean)} s · CI [${fmtPct(p95?.pct_ci_low)}, ${fmtPct(p95?.pct_ci_high)}]`} good={p95 ? (p95.pct_vs_fixed ?? 0) < 0 : null} />
        <Card title="Pedestrian mean wait" value={fmtPct(ped?.pct_vs_fixed)} sub={`${fmt(ped?.mean)} s · CI [${fmtPct(ped?.pct_ci_low)}, ${fmtPct(ped?.pct_ci_high)}]`} good={ped ? (ped.pct_vs_fixed ?? 0) < 0 : null} />
        <Card title="Throughput" value={fmtPct(thr?.pct_vs_fixed)} sub={`${fmt(thr?.mean, 0)} veh/h · CI [${fmtPct(thr?.pct_ci_low)}, ${fmtPct(thr?.pct_ci_high)}]`} good={thr ? (thr.pct_vs_fixed ?? 0) > 0 : null} />
        <Card title="Rickshaw waiting time" value={fmtPct(rick?.pct_vs_fixed)} sub={`${fmt(rick?.mean)} s · the slowest class is not starved`} good={rick ? (rick.pct_vs_fixed ?? 0) < 0 : null} />
        <Card title="Shield interventions per episode" value={fmt(shield?.mean, 2)} sub={`mean over ${n} episodes · reported even when zero`} good={null} />
      </div>
    </section>
  );
}
